#!/usr/bin/env bash
# =====================================================
# code-rules.sh — the mechanical code rules, checked by a machine
# =====================================================
#
#   code-rules.sh                 PreToolUse hook (Edit|Write): blocks a rule break
#   code-rules.sh --diff <dir>    verify.sh step: every rule over the branch diff
#
# These rules used to live only in the code-quality skills and in safety
# invariant 4, and a model forgets prose. A rule that is a text pattern belongs
# to a machine: it never forgets one, it costs nothing, and the reviewer keeps
# its attention for what needs judgement.
#
# Every rule blocks only on an INCREASE, compared file against file — the file
# as it is versus the file as it will be. Keeping, moving or deleting an old
# violation is always allowed, so a legacy file can still be edited.
#
# The hook does not see files written through Bash (heredoc, sed). The --diff
# mode closes that gap: verify.sh runs it over the whole branch, and pr.sh
# commits nothing without a verify PASS.
#
# Paths are taken relative to the git toplevel of the edited file, so the same
# rules apply in the main checkout and in every /ship or review worktree.
#
# Generated by claude-kit: each rule comes from the fragment that owns those
# files. Run .claude/hooks/test-code-rules.sh after ANY edit to the rules.
# =====================================================
set -uo pipefail

MODE="hook"
case "${1:-}" in
  --diff) MODE="diff"; DIFF_DIR="${2:?usage: code-rules.sh --diff <workdir>}" ;;
esac

TMP=$(mktemp -d "${TMPDIR:-/tmp}/code-rules.XXXXXX")
trap 'rm -rf "$TMP"' EXIT

# =====================================================
# RULES
# =====================================================
# include / exclude are space-separated globs relative to the repo root, where
# `*` also matches `/` — `src/*.cs` is every .cs file at any depth under src/.
RULE_ID=(); RULE_INC=(); RULE_EXC=(); RULE_PAT=(); RULE_MSG=()
rule() { RULE_ID+=("$1"); RULE_INC+=("$2"); RULE_EXC+=("$3"); RULE_PAT+=("$4"); RULE_MSG+=("$5"); }

rule 'backend-ts-suppress' \
  'apps/api/src/*.ts apps/api/*.spec.ts apps/api/test/*.ts' \
  '' \
  '@ts-ignore|@ts-expect-error|@ts-nocheck|eslint-disable' \
  'A suppressed type or lint error. Never reach green by disabling a check (safety invariant 4) — fix the code the checker is pointing at.'
rule 'backend-any' \
  'apps/api/src/*.ts' \
  'apps/api/*.spec.ts apps/api/test/*.ts' \
  ':[[:space:]]*any([^[:alnum:]_$]|$)|[[:space:]]as[[:space:]]+any([^[:alnum:]_$]|$)|<any>|(^|[^[:alnum:]_$])any\[\]' \
  'An '\''any'\'' type. Use the real type, or '\''unknown'\'' and narrow it (widening to any is also safety invariant 4).'
rule 'backend-as-unknown-as' \
  'apps/api/src/*.ts' \
  'apps/api/*.spec.ts apps/api/test/*.ts' \
  'as[[:space:]]+unknown[[:space:]]+as[[:space:]]' \
  'An '\''as unknown as'\'' double cast. It switches the type checker off; parse or construct the real type instead.'
rule 'backend-focused-test' \
  'apps/api/*.spec.ts apps/api/test/*.ts' \
  '' \
  '(^|[^[:alnum:]_.$])(xit|xdescribe|fit|fdescribe)[[:space:]]*\(|(it|describe|test)\.(skip|only)[[:space:]]*\(' \
  'A skipped or focused test. Never reach green by disabling a check (safety invariant 4) — fix the test or stop and report.'
rule 'frontend-ts-suppress' \
  'apps/web/src/*.ts apps/web/src/*.tsx apps/web/*.test.ts apps/web/*.test.tsx apps/web/*.spec.ts apps/web/*.spec.tsx' \
  '' \
  '@ts-ignore|@ts-expect-error|@ts-nocheck|eslint-disable' \
  'A suppressed type or lint error. Never reach green by disabling a check (safety invariant 4) — fix the code the checker is pointing at.'
rule 'frontend-any' \
  'apps/web/src/*.ts apps/web/src/*.tsx' \
  'apps/web/*.test.ts apps/web/*.test.tsx apps/web/*.spec.ts apps/web/*.spec.tsx' \
  ':[[:space:]]*any([^[:alnum:]_$]|$)|[[:space:]]as[[:space:]]+any([^[:alnum:]_$]|$)|<any>|(^|[^[:alnum:]_$])any\[\]' \
  'An '\''any'\'' type. Use the real type, or '\''unknown'\'' and narrow it (widening to any is also safety invariant 4).'
rule 'frontend-as-unknown-as' \
  'apps/web/src/*.ts apps/web/src/*.tsx' \
  'apps/web/*.test.ts apps/web/*.test.tsx apps/web/*.spec.ts apps/web/*.spec.tsx' \
  'as[[:space:]]+unknown[[:space:]]+as[[:space:]]' \
  'An '\''as unknown as'\'' double cast. It switches the type checker off; parse or construct the real type instead.'
rule 'frontend-focused-test' \
  'apps/web/*.test.ts apps/web/*.test.tsx apps/web/*.spec.ts apps/web/*.spec.tsx' \
  '' \
  '(^|[^[:alnum:]_.$])(xit|xdescribe|fit|fdescribe)[[:space:]]*\(|(it|describe|test)\.(skip|only)[[:space:]]*\(' \
  'A skipped or focused test. Never reach green by disabling a check (safety invariant 4) — fix the test or stop and report.'
rule 'ui-raw-button' \
  'apps/web/src/*.tsx' \
  'apps/web/src/components/ui/*' \
  '<button([[:space:]>]|$)' \
  'A raw <button>. Use Button from '\''@/components/ui/button'\'' so every button shares one variant set.'

# Generated and vendored files are never checked: protect-generated-files.sh
# and protect-migrations.sh own them, and a generated EF migration opens with
# a comment no human wrote.
NEVER=('node_modules/' '/drizzle/' '/drizzle/meta/')

never_checked() {
  local p
  for p in "${NEVER[@]}"; do
    [[ "/$1" == *"$p"* ]] && return 0
  done
  return 1
}

# matches_any <relpath> <space-separated globs>
matches_any() {
  local rel="$1" g globs
  read -ra globs <<<"$2"
  [[ ${#globs[@]} -eq 0 ]] && return 1
  for g in "${globs[@]}"; do
    # shellcheck disable=SC2053 — the glob is meant to be unquoted
    [[ "$rel" == $g ]] && return 0
  done
  return 1
}

# Lines that are in $2 but not in $1 — the new offenders, for the message.
added_lines() {
  grep -vxFf <(grep . "$1" 2>/dev/null) "$2" 2>/dev/null | sed 's/^[[:space:]]*//' | head -3
}

# check_pair <relpath> <old file> <new file> — prints one block per violation
check_pair() {
  local rel="$1" old="$2" new="$3" i n o
  never_checked "$rel" && return 0
  for ((i = 0; i < ${#RULE_ID[@]}; i++)); do
    matches_any "$rel" "${RULE_INC[$i]}" || continue
    matches_any "$rel" "${RULE_EXC[$i]}" && continue
    n=$(grep -cE -- "${RULE_PAT[$i]}" "$new" 2>/dev/null); n=${n:-0}
    (( n == 0 )) && continue
    o=$(grep -cE -- "${RULE_PAT[$i]}" "$old" 2>/dev/null); o=${o:-0}
    if (( n > o )); then
      grep -E -- "${RULE_PAT[$i]}" "$old" >"$TMP/old.m" 2>/dev/null
      grep -E -- "${RULE_PAT[$i]}" "$new" >"$TMP/new.m" 2>/dev/null
      printf '✖ [%s] %s (+%s)\n' "${RULE_ID[$i]}" "${RULE_MSG[$i]}" "$((n - o))"
      added_lines "$TMP/old.m" "$TMP/new.m" | sed 's/^/      /'
    fi
  done
}

# =====================================================
# --diff: the whole branch, for verify.sh
# =====================================================
if [[ "$MODE" == "diff" ]]; then
  cd "$DIFF_DIR" || { echo "✖ cannot cd to $DIFF_DIR"; exit 1; }
  ROOT=$(git rev-parse --show-toplevel) || exit 1
  BASE=$(git merge-base HEAD origin/main 2>/dev/null || git rev-parse HEAD)
  # <path at base>|<path now>. A renamed file is compared with its old self,
  # so moving a legacy file does not count its old violations as new.
  FILES=$( { git diff --name-status -M --diff-filter=d "$BASE" \
               | awk -F'\t' '$1 ~ /^R/ { print $2 "|" $3; next } { print $2 "|" $2 }'; \
             git ls-files --others --exclude-standard \
               | awk '{ print "|" $0 }'; } )
  FOUND=0
  while IFS='|' read -r was rel; do
    [[ -z "$rel" || ! -f "$ROOT/$rel" ]] && continue
    if [[ -z "$was" ]] || ! git show "$BASE:$was" >"$TMP/old" 2>/dev/null; then : >"$TMP/old"; fi
    OUT=$(check_pair "$rel" "$TMP/old" "$ROOT/$rel")
    if [[ -n "$OUT" ]]; then
      FOUND=1
      echo "$rel"
      printf '%s\n' "$OUT" | sed 's/^/  /'
    fi
  done <<<"$FILES"
  if (( FOUND )); then
    echo "✖ code rules broken — see .claude/hooks/code-rules.sh for every rule"
    exit 1
  fi
  echo "code rules: clean"
  exit 0
fi

# =====================================================
# HOOK MODE
# =====================================================
INPUT=$(cat)
FILE_PATH=$(jq -r '.tool_input.file_path // empty' <<<"$INPUT")
[[ -z "$FILE_PATH" ]] && exit 0

# The file may not exist yet (a Write creates it), so find the nearest
# directory that does. Physical paths on both sides, or /tmp vs /private/tmp
# on macOS makes the prefix strip below silently fail.
DIR=$(dirname "$FILE_PATH")
while [[ ! -d "$DIR" && "$DIR" != "/" ]]; do DIR=$(dirname "$DIR"); done
ROOT=$(git -C "$DIR" rev-parse --show-toplevel 2>/dev/null) || exit 0
PHYS_DIR=$(cd "$DIR" && pwd -P)
FULL="$PHYS_DIR${FILE_PATH#"$DIR"}"
REL="${FULL#"$ROOT"/}"
[[ "$REL" == "$FULL" ]] && exit 0

# Rebuild the whole file as it will be after this edit.
if [[ -f "$FILE_PATH" ]]; then cp "$FILE_PATH" "$TMP/old"; else : >"$TMP/old"; fi
if jq -e '.tool_input | has("content")' <<<"$INPUT" >/dev/null; then
  jq -r '.tool_input.content' <<<"$INPUT" >"$TMP/new"
else
  jq -r --rawfile f "$TMP/old" '
    .tool_input as $t
    | ($t.old_string // "") as $o
    | ($t.new_string // "") as $n
    | if $o == "" then $f
      elif ($t.replace_all // false) then ($f | split($o) | join($n))
      else ($f | split($o)) as $p | if ($p | length) < 2 then $f else $p[0] + $n + ($p[1:] | join($o)) end
      end
  ' <<<"$INPUT" >"$TMP/new"
fi

OUT=$(check_pair "$REL" "$TMP/old" "$TMP/new")
[[ -z "$OUT" ]] && exit 0
{
  echo "BLOCKED: $REL breaks the project's code rules:"
  printf '%s\n' "$OUT" | sed 's/^/  /'
  echo "  These rules are fixed, not judgement calls. Fix the code; never weaken the rule."
} >&2
exit 2
