#!/usr/bin/env bash
# =====================================================
# list-skills.sh — the inventory of this .claude/ setup
# =====================================================
#
#   list-skills.sh [--full] [--format=md|tsv] [filter]
#
# Prints every skill in `.claude/skills/` with what it does, grouped into
# commands and reference skills. Everything is read from the `SKILL.md`
# frontmatter at run time — there is no list of skill names in this script —
# so a newly added skill appears the moment its file exists, and a renamed or
# deleted one disappears. That is the entire point: the hand-maintained
# rosters in README.md and CLAUDE.md drift, this cannot.
#
# Grouping is derived, not curated:
#   argument-hint present  → a command (you type /<name>)
#   name starts backend-   → backend reference skill (agents load it)
#   name starts frontend-  → frontend reference skill
#   anything else          → shared reference skill
#
#   --full          full descriptions, raw argument hints, model overrides,
#                   paths and bundled scripts/reference files
#   --format=tsv    machine-readable, one skill per line:
#                   group⇥name⇥invocation⇥purpose⇥arghint⇥model⇥path⇥bundled
#   filter          case-insensitive substring match over name + description
#
# Exit code is 0 even when nothing matches the filter — a listing that found
# nothing is an answer, not a failure.
#
# Generated by claude-kit.
# =====================================================
set -uo pipefail

# Fields are joined with US (\x1f), not a tab: tab is IFS whitespace, so bash
# collapses a run of them and an empty field (no argument-hint, no model, no
# bundled files) would silently shift every column after it.
SEP=$'\x1f'

# The skills root is resolved from THIS script's location, never from the cwd
# and never from `git rev-parse`: /ship runs stages inside a linked worktree,
# whose toplevel is not where this .claude/ lives.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SKILLS_DIR="$(cd "$SCRIPT_DIR/../skills" && pwd)"
SKILLS_LABEL="$(basename "$(dirname "$SKILLS_DIR")")/$(basename "$SKILLS_DIR")"

FULL=0
FORMAT=md
FILTER=""

for arg in "$@"; do
  case "$arg" in
    --full|-f)   FULL=1 ;;
    --format=*)  FORMAT="${arg#--format=}" ;;
    --tsv)       FORMAT=tsv ;;
    -h|--help)   awk 'NR > 2 && /^# =====/ { exit } NR > 2' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    --*)         echo "unknown option: $arg" >&2; exit 2 ;;
    *)           FILTER="$arg" ;;
  esac
done

case "$FORMAT" in
  md|tsv) ;;
  *) echo "unknown format: $FORMAT (expected md or tsv)" >&2; exit 2 ;;
esac

# ---------------------------------------------------------------- helpers ---

join_by() {                      # join_by <sep> <item>...
  local sep=$1; shift
  local out="" item
  for item in "$@"; do
    if [[ -z "$out" ]]; then out="$item"; else out="$out$sep$item"; fi
  done
  printf '%s' "$out"
}

# Read one SKILL.md's YAML frontmatter as key<TAB>value lines. Indented
# continuation lines fold into the key above them, so a wrapped description
# still arrives in one piece.
read_frontmatter() {
  awk '
    NR == 1 { if ($0 != "---") exit; next }
    $0 == "---" { exit }
    /^[A-Za-z0-9_-]+:/ {
      key = $0; sub(/:.*/, "", key)
      val = $0; sub(/^[A-Za-z0-9_-]+:[ \t]*/, "", val)
      data[key] = val; order[++n] = key; last = key; next
    }
    /^[ \t]+[^ \t]/ {
      if (last != "") { v = $0; sub(/^[ \t]+/, "", v); data[last] = data[last] " " v }
    }
    END { for (i = 1; i <= n; i++) printf "%s\t%s\n", order[i], data[order[i]] }
  ' "$1"
}

# Strip outer whitespace, then one layer of matching surrounding quotes.
unquote() {
  local s=$1
  s="${s#"${s%%[![:space:]]*}"}"
  s="${s%"${s##*[![:space:]]}"}"
  case "$s" in
    \"*\") s="${s:1:${#s}-2}" ;;
    \'*\') s="${s:1:${#s}-2}" ;;
  esac
  printf '%s' "$s"
}

# Cut the trigger clause off a description. "Use when the user says …" is
# prompt plumbing addressed to Claude, not information for a human reading a
# list. The index > 0 guard matters: backend-code-quality and
# frontend-code-quality OPEN with "Use as a checklist…", and cutting at
# position 0 would leave an empty cell.
cut_trigger() {
  local s=$1 marker head best=-1 idx
  for marker in "Use when" "Use this skill" "Use it when" "Also triggers when" "Triggers on"; do
    head="${s%%${marker}*}"
    [[ "$head" == "$s" ]] && continue
    idx=${#head}
    (( idx == 0 )) && continue
    if (( best < 0 || idx < best )); then best=$idx; fi
  done
  (( best > 0 )) && s="${s:0:best}"
  # A description that OPENS with "Use when creating …" is addressed to Claude
  # too; drop the lead-in so the cell reads as a purpose ("Creating or
  # modifying domain entities …"), the voice the README tables already use.
  # "Use as a checklist …" keeps its opening — there is no sentence behind it.
  if [[ "$s" == "Use when "* ]]; then
    s="${s#Use when }"
    s="$(printf '%s' "${s:0:1}" | tr '[:lower:]' '[:upper:]')${s:1}"
  fi
  s="${s%"${s##*[![:space:]]}"}"
  printf '%s' "$s"
}

# Truncate to roughly $2 characters on a word boundary. Word-at-a-time rather
# than substring arithmetic so a multibyte character (an em dash, or any
# non-Latin description) is never sliced in half, and so "e.g." is never
# mistaken for a sentence end.
truncate_words() {
  local s=$1 max=$2 out="" w
  for w in $s; do
    if [[ -z "$out" ]]; then
      out="$w"
    elif (( ${#out} + 1 + ${#w} <= max )); then
      out="$out $w"
    else
      out="${out}…"
      break
    fi
  done
  printf '%s' "$out"
}

# Pipes break markdown table cells.
escape_cell() {
  local s=$1
  printf '%s' "${s//|/\\|}"
}

# ------------------------------------------------------------- collection ---

ROWS=()
n_cmd=0 n_be=0 n_fe=0 n_sh=0 n_total=0

for skill_file in "$SKILLS_DIR"/*/SKILL.md; do
  [[ -e "$skill_file" ]] || continue
  dir="$(dirname "$skill_file")"
  slug="$(basename "$dir")"
  name="" description="" arghint="" model=""

  while IFS=$'\t' read -r key value; do
    case "$key" in
      name)          name="$(unquote "$value")" ;;
      description)   description="$(unquote "$value")" ;;
      argument-hint) arghint="$(unquote "$value")" ;;
      model)         model="$(unquote "$value")" ;;
    esac
  done < <(read_frontmatter "$skill_file")

  # No frontmatter name — fall back to the directory. shared/ and the empty
  # backend/ frontend/ leftovers never reach here at all: no SKILL.md.
  [[ -z "$name" ]] && name="$slug"

  if [[ -n "$FILTER" ]]; then
    haystack="$(printf '%s %s' "$name" "$description" | tr '[:upper:]' '[:lower:]')"
    needle="$(printf '%s' "$FILTER" | tr '[:upper:]' '[:lower:]')"
    [[ "$haystack" == *"$needle"* ]] || continue
  fi

  if [[ -n "$arghint" ]]; then
    sortkey=1; group="Commands"; (( n_cmd++ ))
  elif [[ "$name" == backend-* ]]; then
    sortkey=2; group="Backend reference"; (( n_be++ ))
  elif [[ "$name" == frontend-* ]]; then
    sortkey=3; group="Frontend reference"; (( n_fe++ ))
  else
    sortkey=4; group="Shared reference"; (( n_sh++ ))
  fi
  (( n_total++ ))

  # Invocation form: /name plus the hint's arguments, explanation tail dropped.
  invocation="$name"
  if [[ -n "$arghint" ]]; then
    args="$(unquote "${arghint%% — *}")"
    [[ "$args" == \(* ]] && args=""          # "(no args — …)" means no args
    args="$(truncate_words "$args" 40)"
    invocation="/$name${args:+ $args}"
  fi

  purpose="$(truncate_words "$(cut_trigger "$description")" 130)"

  bundled="$(cd "$dir" && find . -type f ! -name 'SKILL.md' ! -name '.*' 2>/dev/null \
              | sed 's|^\./||' | sort | paste -sd ',' - | sed 's/,/, /g')"

  ROWS+=("$(printf "%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s${SEP}%s" \
    "$sortkey" "$group" "$name" "$invocation" "$purpose" "$arghint" "$model" \
    "$SKILLS_LABEL/$slug/SKILL.md" "$bundled" "$slug")")
done

if (( n_total == 0 )); then
  [[ "$FORMAT" == md ]] && echo "No skills match \`$FILTER\`."
  exit 0
fi

SORTED=()
while IFS= read -r line; do SORTED+=("$line"); done < <(
  printf '%s\n' "${ROWS[@]}" | LC_ALL=C sort -t"$SEP" -k1,1n -k3,3
)

# ----------------------------------------------------------------- output ---

if [[ "$FORMAT" == tsv ]]; then
  for line in "${SORTED[@]}"; do
    IFS="$SEP" read -r _ group name invocation purpose arghint model path bundled _slug <<<"$line"
    printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
      "$group" "$name" "$invocation" "$purpose" "$arghint" "$model" "$path" "$bundled"
  done
  exit 0
fi

if [[ -n "$FILTER" ]]; then
  echo "# Skills matching \`$FILTER\`"
  echo
  printf '_%d of the skills in `%s` match — ' "$n_total" "$SKILLS_LABEL"
else
  echo "# Skills in this setup"
  echo
  printf '_%d skills in `%s` — ' "$n_total" "$SKILLS_LABEL"
fi
parts=()
(( n_cmd )) && parts+=("$n_cmd command$( (( n_cmd == 1 )) || echo s )")
(( n_be ))  && parts+=("$n_be backend")
(( n_fe ))  && parts+=("$n_fe frontend")
(( n_sh ))  && parts+=("$n_sh shared")
printf '%s. Generated from the `SKILL.md` frontmatter._\n' "$(join_by ', ' "${parts[@]}")"

current=""
for line in "${SORTED[@]}"; do
  IFS="$SEP" read -r sortkey group name invocation purpose arghint model path bundled slug <<<"$line"

  if [[ "$group" != "$current" ]]; then
    current="$group"
    case "$sortkey" in
      1) count=$n_cmd; col1="Command"; col2="What it does" ;;
      2) count=$n_be;  col1="Skill";   col2="What it teaches" ;;
      3) count=$n_fe;  col1="Skill";   col2="What it teaches" ;;
      *) count=$n_sh;  col1="Skill";   col2="What it teaches" ;;
    esac
    echo
    echo "## $group ($count)"
    if (( ! FULL )); then
      echo
      echo "| $col1 | $col2 |"
      echo "|---|---|"
    fi
  fi

  if (( FULL )); then
    echo
    echo "### \`$invocation\`"
    meta=()
    [[ -n "$arghint" ]] && meta+=("**Args:** \`$arghint\`")
    [[ -n "$model" ]]   && meta+=("**Model:** \`$model\`")
    meta+=("\`$path\`")
    [[ -n "$bundled" ]] && meta+=("**Bundled:** $bundled")
    join_by '  ·  ' "${meta[@]}"; echo
    echo
    # Full description, re-read from the file so nothing is truncated.
    awk '
      NR == 1 { if ($0 != "---") exit; next }
      $0 == "---" { exit }
      /^[A-Za-z0-9_-]+:/ {
        key = $0; sub(/:.*/, "", key)
        val = $0; sub(/^[A-Za-z0-9_-]+:[ \t]*/, "", val)
        if (key == "description") { printf "%s", val; hit = 1; last = 1 } else last = 0
        next
      }
      /^[ \t]+[^ \t]/ { if (last) { v = $0; sub(/^[ \t]+/, "", v); printf " %s", v } }
      END { if (hit) printf "\n" }
    ' "$SKILLS_DIR/$slug/SKILL.md"
  else
    printf '| `%s` | %s |\n' "$(escape_cell "$invocation")" "$(escape_cell "$purpose")"
  fi
done

# Footer: the non-skill includes, globbed so the count stays honest.
shared_files=()
for f in "$SKILLS_DIR"/shared/*.md; do
  [[ -e "$f" ]] || continue
  shared_files+=("$(basename "$f" .md)")
done
if (( ${#shared_files[@]} )) && [[ -z "$FILTER" ]]; then
  echo
  echo "---"
  echo
  printf '`%s/shared/` holds %d non-skill includes loaded by the skills above, not runnable on their own: %s.\n' \
    "$SKILLS_LABEL" "${#shared_files[@]}" "$(join_by ', ' "${shared_files[@]}")"
fi
